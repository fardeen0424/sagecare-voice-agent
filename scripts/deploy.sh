#!/usr/bin/env bash
# Deploys the latest main on the GPU server: pull, download missing weights, build and start the
# services, wait until all are healthy, then run the end-to-end check. Safe to re-run.
set -euo pipefail
cd /srv/voice

# Pull first, then re-exec so the freshly pulled version of this script is the one that runs.
if [ "${1:-}" != "--pulled" ]; then
  git pull --ff-only
  exec "$0" --pulled
fi

[ -f .env ] || { echo ".env missing: copy .env.example to .env and fill it in."; exit 1; }
env_default () { grep -q "^$1=." .env || { sed -i "/^$1=/d" .env; echo "$1=$2" >> .env; }; }   # keeps set values
domain="$(hostname -I | awk '{print $1}').compute.verda.run"   # Verda's free DNS name for the public IP
env_default LIVEKIT_DOMAIN "$domain"
env_default LIVEKIT_URL "wss://$(sed -n 's/^LIVEKIT_DOMAIN=//p' .env)"
env_default LIVEKIT_API_KEY "API$(openssl rand -hex 6)"
env_default LIVEKIT_API_SECRET "$(openssl rand -hex 32)"
mkdir -p .cache/vllm .cache/tts data/tts-voices logs # Docker would create them root-owned
./scripts/download_models.sh

compose="docker compose -f infra/docker-compose.yml"
echo "Starting services (first start on a new GPU compiles kernels for several minutes)..."
$compose up -d --build --remove-orphans --wait --wait-timeout 1800 \
  || { $compose ps -a; $compose logs --tail 60; echo "A service did not become healthy."; exit 1; }

# One fixed voice for every request; without a reference S2 Pro samples a new speaker each time.
curl -fsS -o /dev/null http://127.0.0.1:8002/v1/audio/voices -F name=sage -F audio_sample=@infra/tts/voices/sage.wav \
  -F "ref_text=$(cat infra/tts/voices/sage.txt)" -F "consent=synthetic voice generated by Fish S2 Pro, no real person"

$compose exec -T stt python - 1 < scripts/check.py
$compose exec -T agent python caller.py 2 # a simulated call through LiveKit and the agent
echo "Deploy OK: $(git log --oneline -1)"
